import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {mileageSummary,drivingMileageHtml,drivingMileageMarkdown} from './guide-driving-mileage.mjs';
const read=name=>fs.readFileSync(new URL(name,import.meta.url),'utf8');
const context={window:{}};
vm.createContext(context);
vm.runInContext(read('guide-cuoqin-plan.js'),context);
const plan=context.window.TIBET_CUOQIN_PLAN;
const evidence=JSON.parse(read('guide-driving-mileage.json'));
const summary=mileageSummary(evidence,plan.days);
assert.equal(evidence.query_date,'2026-10-06');
assert.equal(evidence.days.length,9,'nine driving dates; unprovided city driving is omitted');
assert.equal(summary.rows.length,10,'all ten calendar dates are displayed');
assert.equal(summary.rows.find(row=>row.date==='2026-10-03').km,undefined);
assert.equal(summary.airport,119.3);
const before=evidence.days.find(day=>day.date==='2026-09-30');
const after=evidence.days.find(day=>day.date==='2026-10-01');
assert.ok(before.route.at(-1).includes('琼宗')&&after.route[0].includes('琼宗'),'overnight hotel connects both days');
assert.equal(new URL(before.url).searchParams.get('did'),'B0IUTK0X0R');
assert.equal(new URL(after.url).searchParams.get('fid'),'B0IUTK0X0R');
assert.ok(before.route.some(stop=>stop.includes('扎日'))&&after.route.some(stop=>stop.includes('色林')),'hotel change preserves selected sightseeing waypoints');
assert.ok(!evidence.days.some(day=>day.route.some(stop=>stop.includes('尚客优'))),'unused Nyima hotel is excluded from every mileage route');
assert.equal(summary.total,evidence.total_km,'stored evidence total matches displayed sum');
assert.equal(summary.loop,evidence.loop_km);
for(const day of evidence.days){
  const params=new URL(day.url).searchParams;
  assert.equal(params.get('policy'),'1','consistent selected default route policy');
  assert.ok(params.get('fid')&&params.get('did'),'exact endpoints are retained');
  assert.ok(plan.days.find(item=>item.date===day.date).drive.includes(String(day.km)),'daily card uses the evidence distance');
}
const html=drivingMileageHtml(evidence,plan.days);
const md=drivingMileageMarkdown(evidence,plan.days);
assert.ok(html.includes('未计入')&&md.includes('未计入'),'missing mileage is not silently treated as zero');
assert.ok(read('tibet-cuoqin-guide.html').includes(html),'HTML contains the complete generated mileage section');
assert.ok(read('tibet-cuoqin-guide.md').includes(md.replace(/^## /,'### ')),'Markdown contains the complete mileage evidence nested under the overview');
const publishedHtml=read('tibet-cuoqin-guide.html');
const overview=publishedHtml.match(/<section\b[^>]*id="overview"[^>]*>([\s\S]*?)<\/section>/)?.[1]||'';
assert.ok(overview.includes(html),'complete daily mileage evidence belongs to the overview');
const publishedMd=read('tibet-cuoqin-guide.md');
assert.ok(publishedMd.indexOf('### 每日自驾公里数')>publishedMd.indexOf('## 全程概览')&&publishedMd.indexOf('### 每日自驾公里数')<publishedMd.indexOf('## 天气与穿衣'),'mileage precedes the next top-level chapter');
assert.ok(evidence.scope.basis.includes('历史'),'planning-versus-history limitation is retained');
assert.ok(!read('tibet-cuoqin-guide.html').includes('当天还要经文布南村到尼玛'),'spot advice matches village lodging');
console.log(`Mileage checks passed: 9 routes, 10 dates, ${summary.total.toFixed(1)} km; actual hotel endpoints agree.`);
